@dataclass
class InvoiceData:
    """Structured invoice fields extracted from a PDF.

    Every field except `confidence` is `None` when the model couldn't find it
    on the invoice — the caller (SupplierInvoiceOcrService) skips null fields
    when building the Moco PATCH payload. `confidence` is the model's own
    overall extraction confidence and is used by the service to decide
    whether to surface a "please review" Telegram alert.
    """

    supplier_name: str | None
    supplier_address: str | None
    invoice_date: str | None
    due_date: str | None
    invoice_number: str | None
    total_amount: float | None
    net_amount: float | None
    vat_amount: float | None
    vat_rate: float | None
    currency: str | None
    iban: str | None
    qr_reference: str | None
    # ISO 11649 SCOR (Structured Creditor Reference) — `RF<2 check digits><up
    # to 21 alphanumerics>`. Used on plain (non-QR) bank transfers where the
    # supplier wants payments reconciled against an invoice id. Distinct from
    # `qr_reference` (Swiss QR-bill, exactly 27 digits, requires a QR-IBAN).
    creditor_reference: str | None
    payment_purpose: str | None
    description: str | None
    # The line-item / purchase title, in German and already capped at the
    # 80 chars `BexioExpenseSyncService` truncates to. Distinct from
    # `description`, which stays a pure reading of the document: when the
    # draft was uploaded by hand the operator's subject line (the
    # BUSINESS PURPOSE — "Mittagessen 20.8." on a restaurant receipt, a
    # thing no OCR can infer) is folded in here by the model, joined with
    # a plain ASCII hyphen (Bexio rejects an em dash). None when the
    # model omitted it; callers fall back to `description`.
    position_title: str | None
    # Gutschrift / Rechnung discriminator. Defaults to False (the common
    # case) so callers can branch with `if invoice.is_credit_note: ...`
    # without juggling Optional[bool] semantics. A true credit note ends
    # up booked differently in Moco/Bexio (negative gross_total, "GS-"
    # numbering prefix), so getting this wrong silently is worse than
    # not extracting it.
    is_credit_note: bool
    # Project / site identifier ("Kommission", "Objekt", "Auftragsnummer",
    # "Bauvorhaben") — used downstream to auto-assign the resulting
    # purchase to the matching Moco project. Optional: many supplier
    # invoices don't carry one, and we don't want to invent a value.
    commission: str | None
    # Delivery / shipping address ("Lieferadresse" / "Baustelle") —
    # often the site address that pairs with the Kommission. Different
    # from `supplier_address` (which is the supplier's own HQ).
    delivery_address: str | None
    # True when the document shows the bill was ALREADY settled via a
    # card payment — credit card, debit card / EC-Karte, Maestro, Visa,
    # Mastercard, TWINT, or a POS / EFT terminal slip. Drives the Moco
    # `payment_method` to `credit_card` and suppresses the IBAN / reference
    # / due_date payload fields (the bill is closed; there's no outbound
    # transfer to schedule). Default False — a regular open invoice with
    # an IBAN-and-QR Zahlteil is NOT "already paid".
    already_paid_by_card: bool
    confidence: float


@dataclass
class EnergyBillData:
    """Structured fields from a smart-me Energiekostenabrechnung PDF.

    A much narrower schema than `InvoiceData`: these documents are
    PVcontracting's own outgoing energy statements (generated by
    smart-me), and the downstream consumer
    (`SmartmeEnergyExpenseService`) only needs the site identifier, the
    net amount, and the billing period to book a project expense. Every
    field except `confidence` is None when not found on the document.
    """

    # The "Objekt" line, verbatim incl. the parenthesized site address —
    # e.g. "Gesamtverbrauch (Hauptstrasse 33 Leimbach)". Drives the
    # project match, so the address portion must not be trimmed.
    objekt: str | None
    net_amount: float | None    # "Netto-Betrag" in CHF (excl. VAT)
    period_from: str | None     # Abrechnungszeitraum start, ISO 8601
    period_to: str | None       # Abrechnungszeitraum end, ISO 8601
    invoice_date: str | None    # Rechnungsdatum, ISO 8601
    invoice_number: str | None  # Rechnungsnummer
    confidence: float


@dataclass
class EnergyCreditNoteData:
    """Structured fields from the *production credit* section of an EVU
    statement (e.g. CKW's quarterly "Ihre Gutschrift" PDF).

    These documents often combine a small consumption invoice
    ("Energiebezug"/"Rechnung") with a much larger production credit
    ("Rücklieferung"/"Gutschrift") in the SAME PDF. The bookable amount is
    the document's TOP-LEVEL gross total (e.g. "Ihre Gutschrift" /
    "Gutschriftsbetrag (inkl. MWST)") — it already nets the two sections
    together and is the actual amount that moves; a subsection's own
    Nettobetrag would overstate or understate the credit (see
    `specs/SPEC_energy_credit_note.md`, decision D6). `objekt` is the
    exception: it still comes from the production/credit section
    specifically, since that's what identifies the site for project
    matching — with `objekt_top_level` as a fallback (decision D7) for
    documents where the production section's own Objekt is a generic
    label with no site identifier (e.g. vZEV community "Überschuss"
    pages). Every field except `confidence` is None when not found.
    """

    # The Objekt line from the Rücklieferung/Gutschrift section
    # specifically (e.g. "Produktion PVA HEIV Meierhofweg 10") — NOT the
    # Objekt of a same-document consumption/Eigenbedarf section, which
    # can differ within the same PDF. This is the PRIMARY project-matching
    # signal (see `EnergyCreditNoteService.process`'s fallback to
    # `objekt_top_level` below when this one fails to match).
    objekt: str | None
    # The Objekt line from the document's TOP-LEVEL summary (e.g. "Ihre
    # Gutschrift" / "Objekt: vZEV Krugel 1 Oberkirch") — a FALLBACK
    # project-matching signal, tried only when `objekt` fails to match.
    # Confirmed live (draft 3143993) that some vZEV community statements
    # print a generic, non-site-specific Objekt on the production section
    # ("vZEV Überschuss") while the top-level summary's Objekt carries the
    # actual site name — see `specs/SPEC_energy_credit_note.md`, D7.
    objekt_top_level: str | None
    # The document's TOP-LEVEL Gutschriftsbetrag (inkl. MWST) — e.g. "Ihre
    # Gutschrift CHF 3'785.65" — NOT the production section's own
    # Nettobetrag. Always normalized to a POSITIVE magnitude (the amount
    # owed TO PVcontracting) regardless of how the source EVU prints the
    # sign — confirmed live that some suppliers (EGBB) frame their entire
    # statement as a negative payout/deduction figure (e.g. "Elektrizität
    # Rücklieferung -908.25") while others (CKW) print it as a plain
    # positive total. See `_to_energy_credit_note_data`. The bookable
    # ex-VAT amount is DERIVED from this, not OCR'd — see
    # `_derive_net_amount` in `energy_credit_note_service.py`:
    # `net_amount = gross_amount / (1 + vat_rate)`.
    gross_amount: float | None
    vat_rate: float | None      # decimal, e.g. 0.081 — also drives the net-amount derivation above
    period_from: str | None     # Abrechnungszeitraum start of that section, ISO 8601
    period_to: str | None       # Abrechnungszeitraum end of that section, ISO 8601
    invoice_date: str | None    # Rechnungsdatum, ISO 8601
    invoice_number: str | None  # Rechnungs-Nr
    confidence: float


class AnthropicOcrError(Exception):
    """Raised on any non-2xx from Anthropic or on a malformed model response.

    `status_code` is the HTTP status when the failure was an Anthropic API
    error, or `None` when the API returned 200 but the model's text wasn't
    parseable as JSON / didn't conform to the expected shape. The endpoint
    dispatcher uses this to map 4xx → application error and 5xx → 502.
    """

    def __init__(self, message: str, *, status_code: int | None = None,
                 body: str | None = None):
        super().__init__(message)
        self.status_code = status_code
        self.body = body


