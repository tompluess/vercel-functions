def _str_or_none(value) -> str | None:
    if value is None:
        return None
    s = str(value).strip()
    return s or None


def _bool_or_false(value) -> bool:
    """Coerce the model's `is_credit_note` to a real bool.

    Sonnet usually returns native booleans, but occasionally emits the
    strings "true"/"false" or "yes"/"no" — accept those too. Anything
    unrecognized (including None / missing field) defaults to False,
    which is the safe baseline since most supplier documents are invoices.
    """
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        return value.strip().lower() in {"true", "yes", "ja", "1"}
    return False


def _float_or_none(value) -> float | None:
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _abs_or_none(value: float | None) -> float | None:
    return None if value is None else abs(value)


QR_REFERENCE_LENGTH = 27

# "Modulo 10, rekursiv" — the check-digit algorithm Swiss QR/ESR
# references use. The 27th digit is a checksum over the first 26, so a
# transcription error that happens to preserve the length is still
# catchable. Table per the Six Payment Services ISR specification;
# verified against four live references from Moco purchases (Solarmarkt,
# smart-me, Krannich, Solar Manager) — all four check out.
_QR_CHECK_TABLE = (0, 9, 4, 6, 8, 2, 7, 1, 3, 5)


def _normalize_qr_reference(value) -> str | None:
    """QR-Referenznummer stripped to digits only — exactly 27 digits or None.

    The Swiss QR-bill payment slip prints the 27-digit reference in groups
    (`XX XXXXX XXXXX XXXXX XXXXX XXXXX`), and Sonnet sometimes echoes those
    spaces in its JSON output even though the prompt says "no spaces". The
    canonical form is digits-only — strip anything else so downstream
    consumers (Moco `reference`, Bexio QR payment) never see a formatted
    variant.

    Length is enforced strictly: anything other than 27 digits returns None
    (with a warning logged) so we don't push a broken reference into Moco
    that would silently mis-route the eventual QR payment. The model's
    confidence score plus the Telegram review alert is the human-facing
    signal that a field was dropped; the operator can correct it in the
    Moco draft.

    The **check digit** is verified too. Length alone let a
    length-preserving misread through — and those happen: on one live
    document the model transcribed `...000000339080540 24177` for
    `...000000033908054024177`, dropping a zero from the long zero-run.
    That one was caught by length, but the same slip landing on a digit
    instead of a zero-run would not have been, and a wrong reference is a
    payment posted against the wrong invoice at the supplier. Same
    posture as `_normalize_iban`'s mod-97 gate: refuse rather than guess.
    """
    if value is None:
        return None
    cleaned = "".join(c for c in str(value) if c.isdigit())
    if not cleaned:
        return None
    if len(cleaned) != QR_REFERENCE_LENGTH:
        logger.warning("OCR returned QR-reference with wrong length: "
                       "%d digits (expected %d), nulling field. raw=%r",
                       len(cleaned), QR_REFERENCE_LENGTH, value)
        return None
    expected = _qr_check_digit(cleaned[:-1])
    if int(cleaned[-1]) != expected:
        logger.warning("OCR returned QR-reference with a bad check digit "
                       "(%s, expected %d), nulling field. raw=%r",
                       cleaned[-1], expected, value)
        return None
    return cleaned


def _qr_check_digit(first_26: str) -> int:
    """Modulo-10-recursive check digit over the first 26 digits."""
    carry = 0
    for digit in first_26:
        carry = _QR_CHECK_TABLE[(carry + int(digit)) % 10]
    return (10 - carry) % 10


def is_qr_iban(iban: str | None) -> bool:
    """True if `iban` is a Swiss QR-IBAN.

    Per the Swiss QR-bill spec a QR-IBAN is identified by its IID (bank
    clearing number) in positions 5-9: `30000`-`31999`. Regular IBANs
    have IIDs outside that range, and Moco 422s with
    `"iban":["ist keine QR-IBAN"]` if one is POSTed under
    `payment_method=bank_transfer_swiss_qr_esr`.

    Lives here rather than in `supplier_invoice_ocr_service` (its
    original home) so `PurchaseReviewGate` can use it too — the service
    imports the gate, so the gate cannot import back from the service.
    Sits with the rest of the IBAN knowledge either way.
    """
    if not iban or len(iban) < 9 or not iban.startswith("CH"):
        return False
    iid = iban[4:9]
    if not iid.isdigit():
        return False
    return 30000 <= int(iid) <= 31999


def _normalize_iban(value) -> str | None:
    """IBAN normalized + mod-97 checksum-validated.

    Strips non-alphanum, uppercases (so downstream consumers never see a
    "DE89 3704 ..." formatted variant — same shape Bexio expects, see
    `bexio_expense_sync_service._moco_iban`).

    Then validates the ISO 13616 check digits: rearrange (move first 4
    chars to end), replace letters with their A=10..Z=35 codes, the
    resulting integer must be ≡ 1 (mod 97). Invalid → null + warn.

    Why null on checksum failure: Sonnet occasionally mis-OCRs Swiss
    QR-IBANs that contain alphanumeric characters in the account portion
    (observed: real `CH22 3000 00DE 1611 6572 0` read as
    `CH3909000000161165720` — the model dropped the "00DE" and re-padded
    with digits). The mangled IBAN passes the 21-char length gate but
    fails mod-97; nulling it out is far safer than pushing it to Moco,
    where a wrong IBAN would silently send the QR-bill payment to the
    wrong account.
    """
    if value is None:
        return None
    cleaned = "".join(c for c in str(value) if c.isalnum()).upper()
    if not cleaned:
        return None
    if not _iban_checksum_valid(cleaned):
        logger.warning("OCR returned IBAN with invalid mod-97 checksum, "
                       "nulling field. raw=%r normalized=%r",
                       value, cleaned)
        return None
    return cleaned


SCOR_PREFIX = "RF"
SCOR_MIN_LENGTH = 5    # "RF" + 2 check digits + at least 1 ref char
SCOR_MAX_LENGTH = 25   # "RF" + 2 check digits + up to 21 ref chars


def _normalize_creditor_reference(value) -> str | None:
    """ISO 11649 SCOR (Structured Creditor Reference) normalized + validated.

    Format: `RF<2 check digits><1..21 alphanumeric chars>`, total 5..25
    characters. Strips whitespace, uppercases, then checks mod-97 using the
    same algorithm as IBAN (rearrange first 4 chars to end, map letters
    A=10..Z=35, must be ≡ 1 mod 97). Invalid / wrong length → None.

    The model occasionally returns the reference with the printed spacing
    (`"RF37 R003 2202 6060 7"`); the alnum-strip handles that. Anything
    that survives is safe to put in Moco's `reference` field.
    """
    if value is None:
        return None
    cleaned = "".join(c for c in str(value) if c.isalnum()).upper()
    if not cleaned.startswith(SCOR_PREFIX):
        return None
    if not (SCOR_MIN_LENGTH <= len(cleaned) <= SCOR_MAX_LENGTH):
        return None
    if not cleaned[2:4].isdigit():
        return None
    if not _iban_checksum_valid(cleaned):
        logger.warning("OCR returned creditor_reference with invalid mod-97 "
                       "checksum, nulling field. raw=%r normalized=%r",
                       value, cleaned)
        return None
    return cleaned


def _lift_creditor_reference_from_purpose(purpose: str) -> tuple[str | None, str | None]:
    """If `purpose` contains an ISO 11649 SCOR string, extract it.

    Returns `(scor_or_None, remaining_purpose_or_None)`. The remaining
    purpose has the SCOR substring removed (and surrounding whitespace
    collapsed) — duplicating it in the `info` field would just clutter the
    Moco purchase. Only validated SCORs (mod-97 ok) are lifted; an
    unrelated string starting with "RF" is left alone.
    """
    if not purpose:
        return None, purpose
    import re as _re
    # SCOR printed form: "RF" + 2 digits + groups of uppercase-alphanumerics,
    # often space-separated. Case-sensitive so the regex stops at the first
    # lowercase character (otherwise IGNORECASE would let it greedily eat
    # trailing prose like "RF87 ... 0000 Rechnung Mai" as one match and the
    # subsequent length check would discard the whole capture).
    match = _re.search(
        r"\bRF\d{2}(?:\s*[A-Z0-9]+)+\b",
        purpose,
    )
    if not match:
        return None, purpose
    candidate = _normalize_creditor_reference(match.group(0))
    if candidate is None:
        return None, purpose
    remaining = (purpose[:match.start()] + purpose[match.end():]).strip()
    remaining = _re.sub(r"\s{2,}", " ", remaining)
    return candidate, (remaining or None)


def _iban_checksum_valid(iban: str) -> bool:
    """ISO 13616 mod-97 check.

    Rearrange (first 4 chars to end), replace each letter with its
    A=10, B=11, ..., Z=35 numeric code, treat the resulting digit string
    as one large integer that must be ≡ 1 modulo 97. Pure: no I/O.
    """
    if len(iban) < 4:
        return False
    rearranged = iban[4:] + iban[:4]
    digits: list[str] = []
    for c in rearranged:
        if c.isdigit():
            digits.append(c)
        elif "A" <= c <= "Z":
            digits.append(str(ord(c) - ord("A") + 10))
        else:
            return False
    try:
        return int("".join(digits)) % 97 == 1
    except ValueError:
        return False
